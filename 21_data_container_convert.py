# 列表、元组、字符串、集合、字典的详细对比表
# 以“比较项”为行，“数据容器”为列，便于直观对比
# https://www.bilibili.com/video/BV1zN4y1v7Vv?spm_id_from=333.788.videopod.episodes&vd_source=61f60e39b7cfd78cbfdb31e4997c71af&p=95


# | 比较项         | 列表(list)         | 元组(tuple)         | 字符串(str)         | 集合(set)           | 字典(dict)                |
# |----------------|--------------------|---------------------|---------------------|---------------------|---------------------------|
# | 支持多个元素   | 支持               | 支持                | 支持                | 支持                | 支持                      |
# | 元素类型       | 任意类型           | 任意类型            | 字符（str）         | 不可变类型          | key:不可变，value:任意     |
# | 是否允许重复   | 允许               | 允许                | 允许                | 不允许              | key不允许，value允许       |
# | 是否有序       | 有序               | 有序                | 有序                | 无序                | 无序（3.7+插入有序）       |
# | 是否支持索引   | 支持               | 支持                | 支持                | 不支持              | 不支持                    |
# | 可修改性       | 可变               | 不可变              | 不可变              | 可变                | 可变                      |
# | 使用场景       | 有序可变数据集合   | 有序不可变数据集合  | 文本处理            | 去重、集合运算      | 键值对映射                |
# | 定义符号       | [] 或 list()       | () 或 tuple()       | '' "" 或 str()      | {} 或 set()         | {} 或 dict()              |

# 说明：
# - “有序”指元素的存储顺序与插入顺序一致；“无序”指元素顺序不固定。
# - 集合的{}定义空集时需用set()，否则是字典。
# - 字典的key必须唯一且不可变，value可以任意类型且可重复。
# - Python 3.7及以后，字典的插入顺序会被保留，但本质上仍视为无序。

# 示例代码（可运行验证）：
list1 = [1, 2, 3, 2]
tuple1 = (1, 2, 3, 2)
str1 = "hello"
set1 = {1, 2, 3}
dict1 = {'a': 1, 'b': 2}

print(f"列表：{list1}，类型：{type(list1)}")
print(f"元组：{tuple1}，类型：{type(tuple1)}")
print(f"字符串：{str1}，类型：{type(str1)}")
print(f"集合：{set1}，类型：{type(set1)}")
print(f"字典：{dict1}，类型：{type(dict1)}")
